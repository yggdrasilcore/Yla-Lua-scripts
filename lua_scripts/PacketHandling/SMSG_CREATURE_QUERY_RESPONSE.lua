local function OnMapChange(event, player)
    local mapId = player:GetMapId()
    if mapId == 409 then
        SendRagnarosPacket(player)
    elseif mapId == 649 then
        SendLichKingPacket(player)
    elseif mapId == 724 then
        SendHalionPacket(player)
    end
end

RegisterPlayerEvent(28, OnMapChange)
